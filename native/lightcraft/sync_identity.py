"""Generate the browser's strict engine identity from the managed manifest."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def identity_source(spec):
    return ('// Generated by native/lightcraft/sync_identity.py; edit the manifest instead.\n'
            'export const LIGHTCRAFT_ENGINE = ' + json.dumps(
                {'version': spec['version'], 'commit': spec['commit']}, indent=2) + ' as const;\n')


if __name__ == '__main__':
    spec = json.loads((ROOT / 'native/lightcraft/manifest.json').read_text(encoding='utf-8'))
    (ROOT / 'frontend/src/lightcraftEngine.ts').write_text(identity_source(spec), encoding='utf-8', newline='\n')
